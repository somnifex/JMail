export function readStoredLocale() {
    try {
        return localStorage.getItem(LOCALE_KEY) || DEFAULT_LOCALE;
    } catch {
        return DEFAULT_LOCALE;
    }
}

export function writeStoredLocale(locale) {
    try {
        localStorage.setItem(LOCALE_KEY, locale);
    } catch {
    }
}

export function translate(locale, key, params = {}) {
    const normalizedLocale = locale || DEFAULT_LOCALE;
    const pack = messages[normalizedLocale] || messages[DEFAULT_LOCALE] || {};
    const template = pack[key] || key;
    return template.replace(/\{(\w+)\}/g, (_, token) => (params[token] ?? `{${token}}`));
}

